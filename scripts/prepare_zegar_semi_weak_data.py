"""26.08 -- One-time preprocessing for "Opcja A" (semi-weak supervision, see plans and summaries/
6.08_PODSUMOWANIE_PROCESU.md Etap 32 and the approved plan this implements): turns the 42 raw,
uncropped ZEGAR photos into production-format single-otolith crops the main training pipeline
(src/dataset.py::OtolithDataset) can load directly, plus a small side-table of real ring (x, y)
positions in each crop's own pixel space.

Deliberately produces files SEPARATE from the main data/labels_combined.csv + Z:/Photo/.../Processed
(see cfg.data.zegar_extra_labels_csv/zegar_extra_image_dir/zegar_targets_csv, src/config.py) rather
than writing into them directly -- the main labels CSV is regenerated by scripts/prepare_labels.py on
every RESCAN=True training run (scan of the real Excel + image directory), which would silently drop
any ZEGAR rows written there, disabling zegar_position_weight without any error. Keeping ZEGAR data
in its own files makes it immune to that.

Design decisions (see the approved plan / Etap 32 for full reasoning, not repeated here):
  - NO axis-canonicalization rotation (unlike the earlier from-scratch Option-B experiment) --
    RadialAttentionDensityHead already receives per-image (t, theta) positional encoding computed
    independently by compute_polar_grid, so a physical pixel rotation is unnecessary and would only
    risk new border artifacts.
  - NO background masking at preprocessing time -- OtolithDataset already masks on the fly
    (mask_background=true) for every image, ZEGAR or not; pre-masking would double up / diverge from
    how production images are treated.
  - 42 samples split ~30 "train" (get position supervision) / ~12 "held-out" (excluded from BOTH
    output CSVs entirely -- never enter training in any role) for an honest, non-circular post-hoc
    evaluation via scripts/diagnostics/expert_annotation_eval.py afterward.
  - Both readers' (KK + SS) points used as independent Gaussian centers, UNMATCHED -- same precedent
    already validated in scripts/diagnostics/train_zegar_localization_head.py::build_dataset (their
    heavily-overlapping Gaussians merge into one blob per ring under the "max of Gaussians"
    convention anyway, since sigma=1.2 patches >> the ~4px KK/SS disagreement).

Usage:
    python scripts/prepare_zegar_semi_weak_data.py
"""
