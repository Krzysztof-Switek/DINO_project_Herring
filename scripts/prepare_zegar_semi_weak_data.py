# training will use.
REFERENCE_CONFIG = PROJECT_ROOT / "configs" / "config_radial_attention.yaml"

OUT_IMAGE_DIR = PROJECT_ROOT / "data" / "ZEGAR" / "Processed"
OUT_LABELS_CSV = PROJECT_ROOT / "data" / "zegar_semi_weak_labels.csv"
OUT_TARGETS_CSV = PROJECT_ROOT / "data" / "zegar_semi_weak_targets.csv"
OUT_SPLIT_JSON = PROJECT_ROOT / "data" / "zegar_semi_weak_split.json"

SEED = 42                 # matches this project's standing seed convention
HELDOUT_FRACTION = 0.28   # ~12/42 -- see module docstring for why these are excluded entirely

