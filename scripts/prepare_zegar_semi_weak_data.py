def build_crops(ann: pd.DataFrame, seg_params: dict) -> dict:
    """Crop every sample once (no masking, no rotation -- see module docstring), save to
    OUT_IMAGE_DIR, and return {sample: {"age": int, "points": [(x, y), ...]}} in the SAVED crop's
    own pixel space. Samples where cropping fails are silently excluded (same graceful-degradation
    philosophy as every other ZEGAR diagnostic script)."""
    OUT_IMAGE_DIR.mkdir(parents=True, exist_ok=True)
    samples = sorted(ann["Sample"].unique())
    data: dict = {}
    n_failed = 0
    for i, sample in enumerate(samples, 1):
        raw_image_id = f"{sample}.jpg"   # to read the RAW, uncropped ZEGAR photo
        sub = ann[ann.Sample == sample]
        mean_xy = (float(sub.x.mean()), float(sub.y.mean()))
        raw_rgb = np.array(PILImage.open(ev.IMAGE_DIR / raw_image_id).convert("RGB"), dtype=np.uint8)
        cropped, x0, y0, _used_second = ev.resolve_and_crop_target_otolith(raw_rgb, mean_xy, seg_params)
        if cropped is None:
            print(f"  [{i}/{len(samples)}] {sample}: crop failed, skipping")
            n_failed += 1
            continue

        ages = sub["age"].unique()
        if len(ages) > 1:
            print(f"  [{i}/{len(samples)}] {sample}: WARNING readers disagree on age {ages}, "
                  f"using {int(ages[0])}")
        age = int(ages[0])

        points = [(float(row.x - x0), float(row.y - y0)) for row in sub.itertuples()]

        # "ZEGAR_" prefix is NOT cosmetic: OtolithDataset's mask cache
        # (data/masks_cache/<stem>_mask.png) keys purely by filename stem, with no
        # awareness of directory or image shape. A processed crop saved as plain
        # "Z01.jpg" would collide with any mask ever cached under that same stem for
        # the RAW, differently-shaped ZEGAR photo (confirmed happening in practice:
        # a stale data/masks_cache/Z01_mask.png from an earlier, unrelated run is
        # 2880x2048 vs this crop's ~750x1600, causing a shape-mismatch crash the
        # first time OtolithDataset tried to mask this file). The prefix guarantees
        # the stem can never collide with the raw sample name.
        out_image_id = f"ZEGAR_{sample}.jpg"
        out_path = OUT_IMAGE_DIR / out_image_id
        PILImage.fromarray(cropped).save(out_path, quality=95)

        data[sample] = {"image_id": out_image_id, "age": age, "points": points}
        print(f"  [{i}/{len(samples)}] {sample}: OK ({len(points)} points, age={age}, "
              f"crop={cropped.shape[1]}x{cropped.shape[0]}) -> {out_image_id}")
    print(f"Built {len(data)}/{len(samples)} crops ({n_failed} failed)")
    return data


def make_split(samples: dict, seed: int, heldout_fraction: float) -> tuple[list[str], list[str]]:
    """Age-stratified random split -- held-out samples are EXCLUDED from training entirely (see
    module docstring), so this must be decided ONCE, deterministically, and saved for the later
    evaluation step to know which samples are honestly never-seen-in-training."""
    rng = np.random.RandomState(seed)
    by_age: dict[int, list[str]] = {}
    for sample, info in samples.items():
        by_age.setdefault(info["age"], []).append(sample)

    held_out: list[str] = []
    for age, group in by_age.items():
        group = sorted(group)
        rng.shuffle(group)
        n_hold = max(1, round(len(group) * heldout_fraction)) if len(group) >= 2 else 0
        held_out.extend(group[:n_hold])
    held_out = sorted(held_out)
    train = sorted(s for s in samples if s not in held_out)
    return train, held_out


def main() -> None:
    print("=" * 70)
    print("Przygotowanie danych ZEGAR dla semi-slabego nadzoru (Opcja A, 26.08)")
    print("=" * 70)

    print("\n[1/4] Wczytywanie adnotacji (bez core/edge/ostatniego przyrostu, 24.08 fix)...")
    ann = ev.load_expert_annotations()
    ev.validate_annotation_bounds(ann, ev.IMAGE_DIR)

    print("\n[2/4] Wczytanie parametrow segmentacji (z config_radial_attention.yaml)...")
    cfg = load_merged_config(REFERENCE_CONFIG, None)
    seg_params = cfg.segmentation.as_params()

    print("\n[3/4] Crop kazdej z 42 probek (bez maskowania, bez rotacji)...")
    samples = build_crops(ann, seg_params)

    print(f"\n[4/4] Podzial {SEED=}, held-out frakcja={HELDOUT_FRACTION}...")
    train_ids, heldout_ids = make_split(samples, SEED, HELDOUT_FRACTION)
    print(f"  train (dostaja nadzor pozycyjny): {len(train_ids)} -> {train_ids}")
    print(f"  held-out (calkowicie wykluczone z treningu): {len(heldout_ids)} -> {heldout_ids}")

    labels_rows = [
        {"image_id": samples[s]["image_id"], "age": samples[s]["age"], "split": "train"}
        for s in train_ids
    ]
    pd.DataFrame(labels_rows).to_csv(OUT_LABELS_CSV, index=False)

    target_rows = [
        {"image_id": samples[s]["image_id"], "x": x, "y": y}
        for s in train_ids
        for x, y in samples[s]["points"]
    ]
    pd.DataFrame(target_rows).to_csv(OUT_TARGETS_CSV, index=False)

    OUT_SPLIT_JSON.write_text(json.dumps({
        "seed": SEED, "heldout_fraction": HELDOUT_FRACTION,
        "train": train_ids, "held_out": heldout_ids,
    }, indent=2), encoding="utf-8")

    print(f"\nZapisano:")
    print(f"  {OUT_IMAGE_DIR} ({len(samples)} obrazow)")
    print(f"  {OUT_LABELS_CSV} ({len(labels_rows)} wierszy)")
    print(f"  {OUT_TARGETS_CSV} ({len(target_rows)} wierszy)")
    print(f"  {OUT_SPLIT_JSON}")
    print(f"\nNastepny krok: configs/config_zegar_semi_weak.yaml wskazuje na te pliki "
          f"(zegar_extra_labels_csv/zegar_extra_image_dir/zegar_targets_csv); "
          f"main_zegar_semi_weak.py na serwerze uruchamia pelny trening.")


if __name__ == "__main__":
    main()
